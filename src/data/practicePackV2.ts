import { assertValidChart, sectionFromBarSymbols, type Chart, type Root } from '../music'
import type { StyleId } from '../style'
import type { TuneEntry, TuneTag } from '../library/types'

const C: Root = { letter: 'C', accidental: 0 }
const F: Root = { letter: 'F', accidental: 0 }
const G: Root = { letter: 'G', accidental: 0 }
const BB: Root = { letter: 'B', accidental: -1 }
const EB: Root = { letter: 'E', accidental: -1 }
const D: Root = { letter: 'D', accidental: 0 }
const A: Root = { letter: 'A', accidental: 0 }

type Spec = {
  id: string
  title: string
  blurb: string
  tags: readonly TuneTag[]
  key: Root
  tempo: number
  styleId: StyleId
  form?: readonly string[]
  /** Bars as symbol rows; multi-section via `|` section breaks matching form ids. */
  bars: readonly (readonly string[])[]
  sectionBars?: readonly { id: string; label: string; bars: readonly (readonly string[])[] }[]
  meter?: { numerator: number; denominator: number }
}

function chartFromSpec(spec: Spec): Chart {
  const meter = spec.meter ?? { numerator: 4, denominator: 4 }
  const sections =
    spec.sectionBars?.map((s) =>
      sectionFromBarSymbols(s.id, s.label, s.bars.map((row) => [...row]), meter),
    ) ?? [sectionFromBarSymbols('A', 'A', spec.bars.map((row) => [...row]), meter)]
  const next: Chart = {
    version: 1,
    id: spec.id,
    title: spec.title,
    key: spec.key,
    timeSignature: meter,
    defaultTempoBpm: spec.tempo,
    styleHint: spec.styleId,
    form: [...(spec.form ?? ['A'])],
    sections,
  }
  assertValidChart(next)
  return next
}

function entry(spec: Spec): TuneEntry {
  return {
    id: spec.id,
    title: spec.title,
    blurb: spec.blurb,
    tags: spec.tags,
    shelf: 'practice',
    styleId: spec.styleId,
    createChart: () => chartFromSpec(spec),
  }
}

